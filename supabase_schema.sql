-- 3) Run this whole file.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  category text not null,
  price numeric(12,2) not null default 0,
  image text,
  in_stock boolean not null default true,
  stock_quantity integer not null default 0,
  description text,
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone_number text not null,
  delivery_location text not null,
  customer_email text not null,
  payment_method text not null,
  payment_reference text,
  total numeric(12,2) not null,
  status text not null default 'Pending'
    check (status in ('Pending','Confirmed','Processing','Out for delivery','Delivered','Cancelled')),
  items jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

-- Enable Row Level Security.
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.admin_users enable row level security;

-- Public customers can read products.
drop policy if exists "Anyone can read products" on public.products;
create policy "Anyone can read products"
on public.products for select
using (true);

-- Only registered admin users can create/update/delete products.
drop policy if exists "Admins can insert products" on public.products;
create policy "Admins can insert products"
on public.products for insert
to authenticated
with check (exists (
  select 1 from public.admin_users a where a.user_id = auth.uid()
));

drop policy if exists "Admins can update products" on public.products;
create policy "Admins can update products"
on public.products for update
to authenticated
using (exists (
  select 1 from public.admin_users a where a.user_id = auth.uid()
))
with check (exists (
  select 1 from public.admin_users a where a.user_id = auth.uid()
));

drop policy if exists "Admins can delete products" on public.products;
create policy "Admins can delete products"
on public.products for delete
to authenticated
using (exists (
  select 1 from public.admin_users a where a.user_id = auth.uid()
));

-- Customers can submit orders.
drop policy if exists "Anyone can create orders" on public.orders;
create policy "Anyone can create orders"
on public.orders for insert
with check (true);

-- Only admins can view/update orders.
drop policy if exists "Admins can read orders" on public.orders;
create policy "Admins can read orders"
on public.orders for select
to authenticated
using (exists (
  select 1 from public.admin_users a where a.user_id = auth.uid()
));

drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders"
on public.orders for update
to authenticated
using (exists (
  select 1 from public.admin_users a where a.user_id = auth.uid()
))
with check (exists (
  select 1 from public.admin_users a where a.user_id = auth.uid()
));

-- Admin users can read only their own admin row.
drop policy if exists "Admins can read own admin row" on public.admin_users;
create policy "Admins can read own admin row"
on public.admin_users for select
to authenticated
using (user_id = auth.uid());

